"""M6: aggregate all results into report/results_table.md and copy key figures to report/figures/."""
from __future__ import annotations

import os
import shutil

from _common import ROOT, log, make_parser, setup

SCRIPT = "m6_summary"
SECTIONS = [  # (title, results dir, markdown file, figures)
    ("M1 geometry", "m1_geometry", "geometry_stats.md", ["geometry_fans.png", "phantoms.png", "geometry_singular_values.png"]),
    ("M2 baselines", "m2_baselines", "metrics_table.md", ["reconstructions.png", "random_fields_boxplot.png", "gp_coverage95.png"]),
    ("M3 EBM comparison", "m3_ebm", "results_table.md", ["ebm_reconstructions.png", "energy_traces.png", "rhat.png"]),
    ("M4 ablations", "m4_ablations", "ablations_table.md", ["ablation_K.png", "ablation_tau.png", "ablation_sparse.png", "ablation_noise.png"]),
    ("M5 TSU energy", "m5_energy", "energy_table.md", ["energy_sensitivity.png"]),
]


def main():
    ap = make_parser(SCRIPT, __doc__)
    ap.add_argument("--report-dir", default=os.path.join(ROOT, "report"))
    args = ap.parse_args()
    cfg, out = setup(args, SCRIPT)
    rep = args.report_dir if not args.quick else os.path.join(out, "report")
    figdir = os.path.join(rep, "figures")
    os.makedirs(figdir, exist_ok=True)
    suffix = "_quick" if args.quick else ""
    md = ["# Results table (auto-generated by experiments/m6_summary.py)\n",
          "Numbers are copied from `results/*/`; see each directory's `config.yaml`. Missing sections were not run.\n"]
    copied = []
    for title, d, mdf, figs in SECTIONS:
        base = os.path.join(ROOT, "results", d + suffix)
        md.append(f"\n---\n\n# {title}\n")
        path = os.path.join(base, mdf)
        if not os.path.exists(path):
            md.append(f"_not run: {path} missing_\n")
            log(f"missing {path}")
            continue
        txt = open(path).read()
        # demote headings so the document nests
        md.append("\n".join(("#" + l if l.startswith("#") else l) for l in txt.splitlines()) + "\n")
        for f in figs:
            src = os.path.join(base, f)
            if os.path.exists(src):
                shutil.copy(src, os.path.join(figdir, f))
                copied.append(f)
                md.append(f"![{f}](figures/{f})\n")
    with open(os.path.join(rep, "results_table.md"), "w") as fh:
        fh.write("\n".join(md))
    log(f"wrote {rep}/results_table.md; copied {len(copied)} figures")


if __name__ == "__main__":
    main()
